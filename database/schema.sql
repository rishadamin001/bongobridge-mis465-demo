-- All catalog/order/availability data are generated. No real stock or transactions.
-- Run only in a separate disposable learning database if explicitly desired.
-- The static website does not connect to this database or require Supabase.
-- New private schema avoids collisions with earlier v1/v2 classroom exercises.
BEGIN;
CREATE SCHEMA IF NOT EXISTS bongobridge_demo_v3;
REVOKE ALL ON SCHEMA bongobridge_demo_v3 FROM PUBLIC;

CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.products (
  id text PRIMARY KEY CHECK(id ~ '^P[0-9]{3}$'),
  name text NOT NULL, brand text NOT NULL,
  category text NOT NULL CHECK(category IN ('Electronics','Lifestyle','Fashion','Beauty','Home')),
  family text NOT NULL,
  origin text NOT NULL CHECK(origin IN ('China','USA','UK','India')),
  price_bdt numeric(12,2) NOT NULL CHECK(price_bdt>=0),
  weight_kg numeric(10,3) NOT NULL CHECK(weight_kg>0),
  length_cm numeric(10,3) NOT NULL CHECK(length_cm>0),
  width_cm numeric(10,3) NOT NULL CHECK(width_cm>0),
  height_cm numeric(10,3) NOT NULL CHECK(height_cm>0),
  image_path text NOT NULL, description text NOT NULL,
  demo_limit_per_sku integer NOT NULL CHECK(demo_limit_per_sku BETWEEN 1 AND 500)
);
CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.variants (
  product_id text NOT NULL REFERENCES bongobridge_demo_v3.products(id),
  id text NOT NULL, label text NOT NULL, image_path text NOT NULL, image_alt text NOT NULL,
  price_delta_bdt numeric(12,2) NOT NULL DEFAULT 0,
  PRIMARY KEY(product_id,id)
);
CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.sizes (
  product_id text NOT NULL REFERENCES bongobridge_demo_v3.products(id),
  id text NOT NULL, label text NOT NULL,
  price_delta_bdt numeric(12,2) NOT NULL DEFAULT 0,
  weight_multiplier numeric(8,4) NOT NULL DEFAULT 1 CHECK(weight_multiplier>0),
  PRIMARY KEY(product_id,id)
);
CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.bulk_tiers (
  product_id text NOT NULL REFERENCES bongobridge_demo_v3.products(id),
  minimum_product_quantity integer NOT NULL CHECK(minimum_product_quantity BETWEEN 1 AND 500),
  discount_percent numeric(5,2) NOT NULL CHECK(discount_percent BETWEEN 0 AND 100),
  PRIMARY KEY(product_id,minimum_product_quantity)
);
CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.sku_choices (
  product_id text NOT NULL,
  variant_id text NOT NULL,
  size_id text NOT NULL,
  demo_limit integer NOT NULL CHECK(demo_limit BETWEEN 1 AND 500),
  PRIMARY KEY(product_id,variant_id,size_id),
  FOREIGN KEY(product_id,variant_id) REFERENCES bongobridge_demo_v3.variants(product_id,id),
  FOREIGN KEY(product_id,size_id) REFERENCES bongobridge_demo_v3.sizes(product_id,id)
);
CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.cart_lines (
  demo_session_ref text NOT NULL CHECK(demo_session_ref LIKE 'DEMO-%'),
  product_id text NOT NULL, variant_id text NOT NULL, size_id text NOT NULL,
  quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 500),
  PRIMARY KEY(demo_session_ref,product_id,variant_id,size_id),
  FOREIGN KEY(product_id,variant_id,size_id) REFERENCES bongobridge_demo_v3.sku_choices(product_id,variant_id,size_id)
);
CREATE TABLE IF NOT EXISTS bongobridge_demo_v3.orders (
  id text PRIMARY KEY CHECK(id ~ '^BB-DEMO-[0-9]{4,}$'),
  product_id text NOT NULL, variant_id text NOT NULL, size_id text NOT NULL,
  customer_label text NOT NULL CHECK(customer_label LIKE 'Demo shopper %'),
  city text NOT NULL CHECK(city IN ('Dhaka','Chattogram','Sylhet','Khulna','Rajshahi','Barishal','Rangpur','Mymensingh')),
  status_index smallint NOT NULL CHECK(status_index BETWEEN 0 AND 5),
  quantity integer NOT NULL CHECK(quantity BETWEEN 1 AND 500),
  product_group_quantity integer NOT NULL CHECK(product_group_quantity BETWEEN 1 AND 500),
  unit_price_bdt numeric(12,2) NOT NULL CHECK(unit_price_bdt>=0),
  discount_percent numeric(5,2) NOT NULL CHECK(discount_percent BETWEEN 0 AND 100),
  created_at timestamptz NOT NULL,
  amount_bdt numeric(14,2) NOT NULL CHECK(amount_bdt>=0),
  advance_bdt numeric(14,2) NOT NULL CHECK(advance_bdt>=0),
  later_bdt numeric(14,2) NOT NULL CHECK(later_bdt>=0),
  pricing_version text NOT NULL,
  CHECK(product_group_quantity>=quantity),
  CHECK(advance_bdt+later_bdt=amount_bdt),
  FOREIGN KEY(product_id,variant_id,size_id) REFERENCES bongobridge_demo_v3.sku_choices(product_id,variant_id,size_id)
);
-- A production posting service/transaction must enforce the aggregate 500-unit
